//go:build ignore

// input_keysyms_gen writes input_keysyms_table.go: every named xkb keysym that stands for
// one Unicode character, read from xkbcommon's keysym header. Run it with
// `go generate ./internal/platform/linux/` on a machine with libxkbcommon-dev.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
)

const header = "/usr/include/xkbcommon/xkbcommon-keysyms.h"

// "#define XKB_KEY_eacute 0x00e9 /* U+00E9 LATIN SMALL LETTER E WITH ACUTE */".
// Keypad keysyms write "/*<U+0031 DIGIT ONE>*/" instead; those are left out on
// purpose, because typing '1' must not pick KP_1 (it does nothing with Num
// Lock off).
var line = regexp.MustCompile(`^#define XKB_KEY_(\w+)\s+0x([0-9a-fA-F]+)\s*(?:/\*\s*U\+([0-9A-Fa-f]{4,6})\s)?`)

func main() {
	f, err := os.Open(header)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	type entry struct {
		name string
		sym  uint64
		r    uint64
	}
	var out []entry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := line.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		sym, _ := strconv.ParseUint(m[2], 16, 32)
		var r uint64
		switch {
		case m[3] != "":
			r, _ = strconv.ParseUint(m[3], 16, 32)
		case sym >= 0x20 && sym <= 0x7e, sym >= 0xa0 && sym <= 0xff:
			r = sym
		default:
			continue // not a character (F8, Control_L, dead keys, ...)
		}
		out = append(out, entry{m[1], sym, r})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	var b bytes.Buffer
	b.WriteString("// Code generated by input_keysyms_gen.go from xkbcommon-keysyms.h; DO NOT EDIT.\n\n//go:build linux\n\npackage linux\n\n")
	b.WriteString("// keysymNames maps an xkb keysym name to its keysym and the character it types.\nvar keysymNames = map[string]keysymChar{\n")
	for _, e := range out {
		fmt.Fprintf(&b, "\t%q: {0x%x, 0x%x},\n", e.name, e.sym, e.r)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("input_keysyms_table.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
